"""
build_pixel_art.py
Generates pixel-art character portraits, clean diagnosis pictograms,
and station upgrade sprites as scalable pixel-grid SVGs.
"""
import json

def make_pixel_svg(grid, palette, scale=4, extra_css=""):
    rows = [r.strip() for r in grid.strip().split("\n") if r.strip()]
    h = len(rows)
    w = len(rows[0])
    rects = []
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in palette and palette[ch] != 'none':
                color = palette[ch]
                rects.append(f'<rect x="{x*scale}" y="{y*scale}" width="{scale}" height="{scale}" fill="{color}"/>')
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w*scale} {h*scale}" width="100%" height="100%" shape-rendering="crispEdges"{extra_css}>' + ''.join(rects) + '</svg>'
    return svg

