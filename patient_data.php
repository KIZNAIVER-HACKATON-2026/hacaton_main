/**
 * Справочник диагнозов: названия из MySQL, иконки и недостающие записи — локально.
 * Возвращает [id => ['title' => ..., 'icon' => ...]].
 */
function diagnosis_index(): array
{
    static $index = null;
    if ($index !== null) return $index;

    $index = DIAGNOSIS_FALLBACK;

    foreach (db_diagnoses() as $row) {
        $id = (int) $row['diagnosis_id'];
        $index[$id] = [
            'title' => $row['title'],
            'icon'  => DIAGNOSIS_FALLBACK[$id]['icon'] ?? '❓',
        ];
    }

    return $index;
}

/**
 * Пациенты смены.
 *
 * Поля:
 *   symptoms, vitals  — что видит игрок при осмотре
 *   options           — 3 id диагнозов, один из них верный
 *   correct           — id верного диагноза
 *   treatment         — действия в правильном порядке
 *   note              — короткое объяснение после верного диагноза
 */
function get_pixel_portraits(): array {
    static $portraits = null;
    if ($portraits === null) {
        $file = __DIR__ . '/includes/pixel_art.php';
        if (file_exists($file)) {
            require $file;
            $portraits = isset($PIXEL_PORTRAITS) ? $PIXEL_PORTRAITS : [];
        } else {
            $portraits = [];
        }
    }
    return $portraits;
}

function get_pixel_diagnoses(): array {
    static $diagnoses = null;
