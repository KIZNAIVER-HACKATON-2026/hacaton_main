/**
 * Пациент в формате игрового движка: диагнозы уже с названиями из БД.
 */
function game_patients(): array
{
    $index = diagnosis_index();
    $out = [];

    foreach (shift_patients() as $p) {
        $options = [];
        foreach ($p['options'] as $id) {
            $options[] = [
                'id'    => $id,
                'label' => $index[$id]['title'] ?? ('Диагноз #' . $id),
                'icon'  => $index[$id]['icon'] ?? '❓',
            ];
        }

        $out[] = [
            'id'         => $p['id'],
            'fio'        => $p['fio'],
            'short'      => $p['short'],
            'age'        => $p['age'],
            'emoji'      => $p['emoji'],
            'avatarBg'   => $p['avatarBg'],
            'symptoms'   => $p['symptoms'],
            'vitals'     => $p['vitals'],
            'options'    => $options,
            'correct'    => $p['correct'],
            'correctTitle' => $index[$p['correct']]['title'] ?? '—',
            'treatment'  => $p['treatment'],
            'note'       => $p['note'],
        ];
    }

    return $out;
}

/* ==========================================================================
   Совместимость со старыми страницами (patient.php, diagnosis.php)
   ========================================================================== */

function getAllPatients(): array
{
    $index = diagnosis_index();
    $legacy = [];

    foreach (shift_patients() as $p) {
        $diagnoses = [];
        foreach ($p['options'] as $id) {
            $diagnoses[] = [
                'label'   => $index[$id]['title'] ?? ('Диагноз #' . $id),
                'icon'    => $index[$id]['icon'] ?? '❓',
                'correct' => $id === $p['correct'],
            ];
        }

        $legacy[$p['id']] = [
            'id'        => $p['id'],
            'fio'       => $p['fio'],
            'age'       => $p['age'],
            'emoji'     => $p['emoji'],
            'avatarBg'  => $p['avatarBg'],
            'symptoms'  => $p['symptoms'],
            'vitals'    => $p['vitals'],
            'diagnoses' => $diagnoses,
            'treatment' => $p['treatment'],
        ];
    }

    return $legacy;
}

function getPatient(?int $id): array
{
    $all = getAllPatients();
    if ($id !== null && isset($all[$id])) return $all[$id];
    return $all[array_rand($all)];
}
